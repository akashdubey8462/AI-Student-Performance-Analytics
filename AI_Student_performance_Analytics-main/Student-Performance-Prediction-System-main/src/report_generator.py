"""ScholarIQ Report Generator Module.
Produces downloadable academic evaluation reports in plain text, CSV, and HTML formats.
"""
from typing import Dict, Any, List
from datetime import datetime


def generate_text_report(student_data: Dict[str, Any], pred: Dict[str, Any], recs: List[Dict[str, Any]]) -> str:
    """Generate a clean, structured plain-text academic forecast report."""
    now = datetime.now().strftime("%d %B %Y, %H:%M")
    name = student_data.get("Student_Name", "Student")
    gender = "Male" if student_data.get("Gender", 1) == 1 else "Female"
    
    report_lines = [
        "=" * 64,
        "          SCHOLARIQ — ACADEMIC PERFORMANCE FORECAST",
        "         Early Warning & Student Intelligence System",
        "=" * 64,
        f"Generated On  : {now}",
        f"Student Name  : {name}",
        f"Gender        : {gender}   |  Age: {student_data.get('Age', '-')}",
        "-" * 64,
        "INPUT SIGNALS & ACADEMIC INDICATORS:",
        f"  • Attendance Rate       : {student_data.get('Attendance_Percentage', 0):.1f} %",
        f"  • Coursework Submitted  : {student_data.get('Assignments_Submitted', 0)} / 10",
        f"  • Interim Assessment    : {student_data.get('Internal_Marks', 0):.1f} / 10",
        f"  • Daily Study Hours     : {student_data.get('Self_Study_Hours', 0):.1f} hrs/day",
        f"  • Previous Failures     : {student_data.get('Previous_Failures', 0)}",
        f"  • Remedial Classes      : {'Yes' if student_data.get('Extra_Classes', 0) == 1 else 'No'}",
        "-" * 64,
        "MACHINE LEARNING FORECAST (MODEL VERSION: " + str(pred.get('model_version', 'v2_clean')).upper() + "):",
        f"  • Projected Final Score : {pred.get('predicted_score', 0):.1f} / 100",
        f"  • Confidence Interval   : [{pred.get('score_lower', 0):.1f} – {pred.get('score_upper', 0):.1f}] (±{pred.get('uncertainty_margin', 0):.1f} pts)",
        f"  • Projected Grade       : {pred.get('grade', '-')} ({pred.get('performance', '-')})",
        f"  • Risk Classification   : {pred.get('risk_level', '-').upper()}",
        "=" * 64,
        "RECOMMENDED INTERVENTIONS & ACTIONS:"
    ]
    
    for idx, rec in enumerate(recs, 1):
        report_lines.append(f"\n[{idx}] {rec.get('priority', 'ACTION')} — {rec.get('category', 'Category')}")
        report_lines.append(f"    Issue   : {rec.get('issue', '-')}")
        report_lines.append(f"    Student : {rec.get('student_action', '-')}")
        report_lines.append(f"    Faculty : {rec.get('educator_action', '-')}")
        
    report_lines.extend([
        "\n" + "-" * 64,
        "IMPORTANT NOTICE & LIMITATIONS:",
        "This forecast is a statistical estimate generated by machine learning.",
        "It is designed to alert educators and students to potential risks early.",
        "It does NOT guarantee final examination outcomes and must NOT be used",
        "as the sole basis for punitive or final academic grading decisions.",
        "=" * 64
    ])
    
    return "\n".join(report_lines)


def generate_cohort_summary_csv(cohort_df) -> str:
    """Export cohort predictions and risk flags as a CSV string."""
    return cohort_df.to_csv(index=False)
